"""Paper 1 (narrowed) evaluator v2 (PREPARED; Val-A validation pending; UIEB NOT RUN).

Extends the committed, validated evaluator v2_tools/paper1_final_eval.py (imported, NOT modified; its helpers, metrics, policy checks and LPIPS set-up are reused unchanged).
Additions, each required by reports/paper1_narrowed/S0_preregistration.md or by the protocol proposal (reports/paper1_uieb_evaluation_protocol_proposal.md):
  1. 14 further checkpoints for gate G1 (Stage 4A AT-Trunk BN, Arm C BN, Arm D global/grid BN, WWE-UIE no-WB IN/BN): 31 models in total.
  2. --checkpoint best_valA (PRIMARY) | last (CROSS-CHECK). Each file's SHA-256 is compared with result.json before any torch.load.
  3. UIEB manifest loader for the frozen-90 schema: key 'pairs', paths relative to the project root (resolved explicitly), optional per-image recorded hashes
     ('input_sha256', 'gt_sha256'), which are verified BEFORE any image is decoded; any mismatch stops the run.
  4. --uieb-pairing strict (identical basenames, as before) | stem (identical case-sensitive stems, extensions may differ: the rule used when the frozen-90
     manifest was generated by tests/test_pre_training_verification.py). The choice is recorded.
  5. Ledger in a NEW top-level folder paper1_uieb_runs/ledger/: one exclusively created JSON file per event; nothing under reports/ is appended to or overwritten.
  6. The pre-registration file's SHA-256 is verified at start; gate G1 is computed with its thresholds (hard-coded here, checked by the test suite).
  7. For a UIEB run: all 31 models and LPIPS are mandatory (no --models subset, no --no-lpips).
Fail-closed: --dataset uieb needs the exact phrase `UIEB approved` and every UIEB argument from the user (E.check_dataset_policy). Val-A remains the only other dataset.
Usage (Val-A validation): python v2_tools/paper1_final_eval_v2.py --dataset val_A --checkpoint best_valA --out <new dir>"""
