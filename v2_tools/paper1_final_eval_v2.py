STATE = {"out": None, "started": False, "res": None}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--checkpoint", default="best_valA", choices=sorted(CKPT_FILES)); ap.add_argument("--models", default="all"); ap.add_argument("--no-lpips", action="store_true")
    ap.add_argument("--uieb-phrase"); ap.add_argument("--uieb-manifest"); ap.add_argument("--uieb-manifest-sha256"); ap.add_argument("--uieb-expected-pairs", type=int)
    ap.add_argument("--uieb-path-marker"); ap.add_argument("--uieb-pairing", default="strict", choices=["strict", "stem"])
    ap.add_argument("--disclosed-rerun", action="store_true"); ap.add_argument("--rerun-reason")
    a = ap.parse_args(argv)
    E.check_dataset_policy(a.dataset, a.uieb_phrase, (a.uieb_manifest, a.uieb_manifest_sha256, a.uieb_expected_pairs, a.uieb_path_marker))
    if a.dataset == "uieb":
        check_uieb_completeness(a.models, a.no_lpips)
    verify_prereg()
    if a.dataset == "uieb":
        guarded2(lambda: _run(a), STATE, LEDGER_DIR, "uieb")
    else:
        _run(a)


def _run(a):
    is_uieb = a.dataset == "uieb"
    import torch
    import train_v2 as tv
    E.restrict_manifests(tv.MANIFESTS)  # BEFORE any manifest is hashed or read
    keys = list(MODELS) if a.models == "all" else a.models.split(",")
    assert all(k in MODELS for k in keys), keys
    if not is_uieb:
        mp = tv.MANIFESTS["val_A"][0]; mh = E.sha256_file(mp); assert mh.startswith(E.VAL_A_PREFIX), mh
    ckpts = {k: verify_checkpoint2(MODELS[k][0], a.checkpoint) for k in keys}  # all hashes verified before any torch.load
    extra = {}
    if is_uieb:  # first UIEB access: after the phrase, the pre-registration check and all checkpoint hashes
        pairs, mh, extra = load_uieb_manifest2(a.uieb_manifest, a.uieb_manifest_sha256, a.uieb_expected_pairs, a.uieb_path_marker, a.uieb_pairing)
        mp = Path(a.uieb_manifest)
        n_prior = ledger_precheck2(LEDGER_DIR, "uieb", a.disclosed_rerun, a.rerun_reason, a.checkpoint)
        out = E.exclusive_dir(ROOT / a.out); STATE["out"] = str(out)
        ledger_write(LEDGER_DIR, {"event": "started", "dataset": "uieb", "out": str(out), "time": time.strftime("%Y-%m-%d %H:%M:%S"), "earlier_attempts": n_prior,
                                  "rerun_reason": a.rerun_reason, "script_sha256": E.sha256_file(__file__), "manifest_sha256": mh, "checkpoint": a.checkpoint})
        STATE["started"] = True
        hdr = E.header_report(pairs)
        with open(out / "pairs_meta.csv", "x", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(hdr[0])); w.writeheader(); w.writerows(hdr)
        extra["header_summary"] = E.header_summary(hdr)
    else:
        out = E.exclusive_dir(ROOT / a.out)
        pairs = tv.load_pairs("val_A"); assert len(pairs) == 166; E.assert_no_reserved_paths(pairs)
    X, Y = tv.preload(pairs)
    assert X.shape == Y.shape == (len(pairs), 3, 256, 256) and X.dtype == Y.dtype == torch.uint8
    dev = torch.device("cuda")
    lp, lp_info = (None, None) if a.no_lpips else E.build_lpips(dev)
    res, per = {}, {}
    STATE["res"] = res
    for k in keys:
        m = load_model2(k, ckpts[k][0], a.checkpoint, dev)
        ps, ss, ls, nf = E.score_model(m, X, Y, dev, lp)
        res[k] = {"run": MODELS[k][0], "checkpoint": a.checkpoint, "checkpoint_sha256": ckpts[k][1], "psnr": float(ps.mean()), "ssim": float(ss.mean()),
                  "lpips": (float(ls.mean()) if ls is not None else None), "nonfinite_before_clamp": nf}
        if is_uieb:
            res[k]["finite_ok"] = bool(nf == 0 and np.isfinite(ps).all() and np.isfinite(ss).all() and (ls is None or np.isfinite(ls).all()))
            if not res[k]["finite_ok"]:
                raise SystemExit(f"STOP: non-finite outputs/scores for {k}")
        else:
            lg = logged_valA(MODELS[k][0], a.checkpoint)
            res[k].update({"logged_psnr": lg["psnr_mean"], "logged_ssim": lg["ssim_mean"],
                           "matches_logged": bool(abs(ps.mean() - lg["psnr_mean"]) < 1e-3 and abs(ss.mean() - lg["ssim_mean"]) < 1e-4 and nf == 0)})
        per[k] = (ps, ss, ls)
        print(k, {x: (round(y, 5) if isinstance(y, float) else y) for x, y in res[k].items() if x not in ("run", "checkpoint_sha256")}, flush=True)
        del m; torch.cuda.empty_cache()
    with open(out / "per_image.csv", "x", newline="") as f:
        w = csv.writer(f); w.writerow(["filename"] + [f"{k}_{n}" for k in keys for n in (("psnr", "ssim") + (() if lp is None else ("lpips",)))])
        for i, p in enumerate(pairs):
            row = []
            for k in keys:
                row += [f"{per[k][0][i]:.6f}", f"{per[k][1][i]:.6f}"] + ([] if lp is None else [f"{per[k][2][i]:.6f}"])
            w.writerow([p.get("filename", Path(p["input_path"]).name)] + row)
    gate = gate_g1({k: v[0] for k, v in per.items()}) if all(k in per for k in G1_KEYS) else None
    meta = {"created": time.strftime("%Y-%m-%d %H:%M:%S"), "dataset": a.dataset, "checkpoint": a.checkpoint, "n_images": len(pairs), "manifest_sha256": mh, "manifest_path": str(mp),
            "prereg_sha256": PREREG_SHA256, "script": str(Path(__file__).relative_to(ROOT)), "script_sha256": E.sha256_file(__file__),
            "frozen_evaluator_sha256": E.sha256_file(Path(E.__file__)), "command": " ".join(sys.argv),
            "git_head": subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip(),
            "git_dirty_tracked": subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=ROOT, capture_output=True, text=True).stdout.strip().splitlines(),
            "torch": torch.__version__, "numpy": np.__version__, "python": platform.python_version(), "gpu": torch.cuda.get_device_name(0),
            "cudnn_allow_tf32": torch.backends.cudnn.allow_tf32, "lpips": lp_info, **extra,
            "status": (E.UIEB_STATUS if is_uieb else "Val-A validation of evaluator v2 (selection set; exploratory; gate values on Val-A are NOT the pre-registered G1)"),
            **({"protocol_note": E.UIEB_PROTOCOL_NOTE, "candidate_protocol": True} if is_uieb else {})}
    E.write_json_x(out / "summary.json", {"meta": meta, "models": res, "gate_g1": gate})
    print("all_match_logged", None if is_uieb else all(r["matches_logged"] for r in res.values()), "gate", None if gate is None else gate["outcome"], "written", out)


if __name__ == "__main__":
    main()
