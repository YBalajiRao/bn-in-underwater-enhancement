# ----------------------------------------------------------------------------- pure helpers (CPU-tested)
def verify_prereg(path=PREREG, expected=PREREG_SHA256):
    got = E.sha256_file(path)
    if got != expected:
        raise SystemExit(f"STOP: pre-registration {path} sha256 {got} != frozen {expected}")
    return got


def verify_checkpoint2(run_dir, which, root=None):
    """Compare the chosen checkpoint file with result.json's recorded hash; abort on mismatch."""
    if which not in CKPT_FILES:
        raise SystemExit(f"STOP: unknown checkpoint choice {which!r}")
    d = Path(root or (ROOT / "runs_v2")) / run_dir
    fn = CKPT_FILES[which]
    rec = json.load(open(d / "result.json"))["checkpoint_sha256"].get(fn)
    got = E.sha256_file(d / fn)
    if not rec or got != rec:
        raise SystemExit(f"STOP: {run_dir}/{fn} sha256 {got} != recorded {rec}")
    return d / fn, got


def logged_valA(run_dir, which, root=None):
    """Logged Val-A scores for the chosen checkpoint: best -> result.json best_valA; last -> the epoch-99 line of history.jsonl."""
    d = Path(root or (ROOT / "runs_v2")) / run_dir
    if which == "best_valA":
        return json.load(open(d / "result.json"))["best_valA"]
    lines = [json.loads(x) for x in open(d / "history.jsonl") if x.strip()]
    last = max(lines, key=lambda r: r["epoch"])
    epochs = json.load(open(d / "result.json"))["epochs"]
    if last["epoch"] != epochs - 1:
        raise SystemExit(f"STOP: {run_dir} history last epoch {last['epoch']} != {epochs - 1}")
    return last["val_A"]


def state_dict_from(ck, which, expected_last_epoch=None):
    """train_v2 saves best_valA.pth as {'model_state_dict', 'epoch', 'val_A'} and last.pth as {'model', 'opt', 'sched', 'scaler', 'epoch', ...}.
    Return the model weights for the chosen file; for last.pth also require the final epoch."""
    key = {"best_valA": "model_state_dict", "last": "model"}.get(which)
    if key is None or key not in ck:
        raise SystemExit(f"STOP: checkpoint ({which}) has no {key!r} entry; keys {sorted(ck)}")
    if which == "last" and expected_last_epoch is not None and ck.get("epoch") != expected_last_epoch:
        raise SystemExit(f"STOP: last.pth epoch {ck.get('epoch')} != final epoch {expected_last_epoch}")
    return ck[key]


def load_model2(key, ckpt, which, device, root=None):
    import importlib, torch
    run = MODELS[key][0]
    epochs = json.load(open(Path(root or (ROOT / "runs_v2")) / run / "result.json"))["epochs"]
    mod, cls = MODELS[key][1].split(":")
    m = getattr(importlib.import_module(mod), cls)()
    m.load_state_dict(state_dict_from(torch.load(ckpt, map_location="cpu", weights_only=False), which, epochs - 1), strict=True)
    return m.to(device).eval()


def resolve_pairs(pairs, base=ROOT):
    """Absolute paths are kept; relative paths are resolved against the project root (never against the current directory)."""
    out = []
    for p in pairs:
        q = dict(p)
        for k in ("input_path", "gt_path"):
            v = Path(str(p[k]))
            q[k] = str(v if v.is_absolute() else (Path(base) / v))
        out.append(q)
    return out


def validate_pairs2(pairs, expected_n, rule, check_files=True):
    """'strict' delegates to the frozen E.validate_pairs. 'stem': identical case-sensitive stems (extensions may differ); all other checks as in strict."""
    if rule == "strict":
        return E.validate_pairs(pairs, expected_n, check_files)
    if rule != "stem":
        return [f"unknown pairing rule {rule!r}"]
    errs = []
    if len(pairs) != expected_n:
        errs.append(f"pair count {len(pairs)} != expected {expected_n}")
    stems, ins, gts = {}, {}, {}
    for i, p in enumerate(pairs):
        ip = p.get("input_path") if isinstance(p, dict) else None
        gp = p.get("gt_path") if isinstance(p, dict) else None
        if not (isinstance(ip, str) and ip and isinstance(gp, str) and gp):
            errs.append(f"item {i}: missing/empty input_path or gt_path")
            continue
        si, sg = Path(ip).stem, Path(gp).stem
        if si != sg:
            errs.append(f"item {i}: stem mismatch {si!r} vs {sg!r}")
        if E._norm(ip) == E._norm(gp):
            errs.append(f"item {i}: input_path == gt_path")
        for d, key, what in ((stems, si, "stem"), (ins, E._norm(ip), "input_path"), (gts, E._norm(gp), "gt_path")):
            if key in d:
                errs.append(f"item {i}: duplicate {what} {key!r} (also item {d[key]})")
            else:
                d[key] = i
        if check_files:
            for what, path in (("input", ip), ("gt", gp)):
                if not Path(path).is_file():
                    errs.append(f"item {i}: {what} file missing {path!r}")
    return errs


def verify_recorded_hashes(pairs):
    """For pairs carrying recorded 'input_sha256' / 'gt_sha256', recompute and compare. Returns (n_checked_files, mismatches)."""
    n, bad = 0, []
    for i, p in enumerate(pairs):
        for k, hk in (("input_path", "input_sha256"), ("gt_path", "gt_sha256")):
            if p.get(hk):
                n += 1
                got = E.sha256_file(p[k])
                if got != p[hk]:
                    bad.append(f"item {i} {k}: {got} != recorded {p[hk]}")
    return n, bad


def load_uieb_manifest2(path, sha_prefix, expected_n, marker, rule, require_recorded_hashes=True, base=ROOT, lsui_root=None):
    """Called ONLY after authorization, pre-registration check and checkpoint verification. Manifest hash first; then parse, resolve, validate, marker/LSUI-root checks,
    then recorded per-image hashes (all before any pixel decode)."""
    h = E.sha256_file(path)
    if not h.startswith(sha_prefix.lower()):
        raise SystemExit(f"STOP: UIEB manifest sha256 {h} does not start with the expected {sha_prefix}")
    data = json.load(open(path, encoding="utf-8"))
    pairs = data.get("test_pairs") or data.get("pairs")
    if not isinstance(pairs, list):
        raise SystemExit("STOP: UIEB manifest has neither 'test_pairs' nor 'pairs' list")
    pairs = resolve_pairs(pairs, base)
    errs = validate_pairs2(pairs, expected_n, rule, check_files=True)
    if errs:
        raise SystemExit("STOP: UIEB pair validation failed (%d errors); first: %s" % (len(errs), "; ".join(errs[:10])))
    E.assert_uieb_paths(pairs, marker, lsui_root)
    n_chk, bad = verify_recorded_hashes(pairs)
    if bad:
        raise SystemExit("STOP: recorded per-image hashes do not match (%d); first: %s" % (len(bad), "; ".join(bad[:5])))
    if require_recorded_hashes and n_chk != 2 * len(pairs):
        raise SystemExit(f"STOP: recorded per-image hashes present for {n_chk} of {2 * len(pairs)} files")
    meta = {k: v for k, v in data.items() if k not in ("pairs", "test_pairs")}
    return pairs, h, {"recorded_hashes_checked": n_chk, "manifest_meta": meta, "pairing_rule": rule}


def ledger_events(ledger_dir=LEDGER_DIR):
    d = Path(ledger_dir)
    return [json.load(open(f, encoding="utf-8")) for f in sorted(d.glob("*.json"))] if d.exists() else []


def ledger_attempts2(ledger_dir, dataset, checkpoint=None):
    """Attempts for (dataset, checkpoint). best_valA (primary) and last (pre-registered cross-check) are separate planned runs; any repeat of either is disclosed."""
    recs = [r for r in ledger_events(ledger_dir) if r.get("dataset") == dataset]
    res = []
    for r in recs:
        if r["event"] == "started" and (checkpoint is None or r.get("checkpoint") == checkpoint):
            end = [e["event"] for e in recs if e["event"] in ("completed", "failed") and e.get("out") == r.get("out")]
            res.append((r.get("out"), end[-1] if end else "interrupted"))
    return res


def ledger_precheck2(ledger_dir, dataset, allow_rerun, reason, checkpoint=None):
    att = ledger_attempts2(ledger_dir, dataset, checkpoint)
    if att and not allow_rerun:
        raise SystemExit(f"STOP: earlier {dataset} attempt(s) exist {att}; a repeat needs --disclosed-rerun --rerun-reason '...' and a new --out directory")
    if allow_rerun and not (reason and reason.strip()):
        raise SystemExit("STOP: --disclosed-rerun needs a non-empty --rerun-reason")
    return len(att)


def ledger_write(ledger_dir, rec):
    """One new file per event, exclusive create; never appends to or overwrites anything."""
    d = Path(ledger_dir); d.mkdir(parents=True, exist_ok=True)
    p = d / f"{time.strftime('%Y%m%dT%H%M%S')}_{rec['event']}_{uuid.uuid4().hex[:8]}.json"
    with open(p, "x", encoding="utf-8") as f:
        json.dump(rec, f, indent=1)
    return p


def guarded2(fn, state, ledger_dir, dataset):
    now = lambda: time.strftime("%Y-%m-%d %H:%M:%S")  # noqa: E731
    try:
        r = fn()
    except BaseException as e:  # noqa: BLE001
        info = {"event": "failed", "dataset": dataset, "out": str(state.get("out")), "error_type": type(e).__name__, "error": str(e)[:2000], "time": now()}
        if state.get("out") is not None:
            try:
                E.write_json_x(Path(state["out"]) / "failure.json", dict(info, models_scored_so_far=state.get("res"),
                                                                          note="FAILED RUN: diagnostics only. No summary.json exists for this attempt."))
            except Exception as e2:  # noqa: BLE001
                info["failure_json_error"] = repr(e2)
        if state.get("started"):
            ledger_write(ledger_dir, info)
        raise
    if state.get("started"):
        ledger_write(ledger_dir, {"event": "completed", "dataset": dataset, "out": str(state.get("out")), "time": now()})
    return r


def gate_g1(psnr):
    """psnr: {model_key: per-image PSNR array}. Implements S0_preregistration.md section 4 exactly. Seed-wise paired mean differences (dB)."""
    md = lambda a, b: float(np.mean(np.asarray(psnr[a], float) - np.asarray(psnr[b], float)))  # noqa: E731
    mar = [md(f"marinenet_in_s{s}", f"marinenet_bn_s{s}") for s in SEEDS]
    atr = [md(f"attrunk_in_s{s}", f"attrunk_bn_s{s}") for s in SEEDS]
    bn_gain = [md(f"attrunk_bn_amp_s{s}", f"armc_bn_amp_s{s}") for s in SEEDS]
    in_gain = [md(f"attrunk_in_s{s}", f"armcin_s{s}") for s in SEEDS]
    bn_m, in_m = float(np.mean(bn_gain)), float(np.mean(in_gain))
    inter = bn_m - in_m
    ge = lambda x, thr: x >= thr - FLOAT_TOL  # noqa: E731  (floating-point rounding only; 1e-9 dB does not change the pre-registered thresholds)
    a = all(ge(x, G1["norm_min_per_seed"]) for x in mar) and all(ge(x, G1["norm_min_per_seed"]) for x in atr)
    b = ge(bn_m, G1["colour_bn_gain_min"]) and abs(in_m) <= G1["colour_in_gain_abs_max"] + FLOAT_TOL and ge(inter, G1["colour_interaction_min"])
    outcome = "proceed_to_S3" if (a and b) else ("H1_only_redecide" if a else "stop_training_plans")
    return {"thresholds_db": dict(G1), "marinenet_in_minus_bn_per_seed": mar, "attrunk_in_minus_bn_per_seed": atr,
            "colour_gain_bn_per_seed": bn_gain, "colour_gain_in_per_seed": in_gain, "colour_gain_bn_mean": bn_m, "colour_gain_in_mean": in_m,
            "colour_interaction": inter, "G1a_pass": bool(a), "G1b_pass": bool(b), "outcome": outcome,
            "descriptive_wwe_nowb_in_minus_bn_s0": (md("wwe_nowb_in_s0", "wwe_nowb_bn_s0") if "wwe_nowb_in_s0" in psnr and "wwe_nowb_bn_s0" in psnr else None)}


def check_uieb_completeness(models_arg, no_lpips):
    if models_arg != "all" or no_lpips:
        raise SystemExit("STOP: a UIEB run must score all models with LPIPS (no --models subset, no --no-lpips)")


